import SwiftUI

struct MoreFilterOption: View {
    var option: String
    @Binding var isSelected: Bool

    private let stringTable = "DashboardFilter"

    var body: some View {
        VStack {
            HStack {
                if isSelected {
                    Image(systemName: "checkmark")
                        .foregroundColor(.more.approved)
                } else {
                    Spacer()
                        .frame(width: 5)
                }
                MoreFilterText(text: .constant(option))
            }
            .padding(5)
        }
    }
}
